function esc(value: string): string {
  return value.replace(/[&<>"']/g, (ch) => {
    switch (ch) {
      case '&': return '&amp;';
      case '<': return '&lt;';
      case '>': return '&gt;';
      case '"': return '&quot;';
      default: return '&#39;';
    }
  });
}

function number(value: number): string {
  if (!Number.isFinite(value)) return '—';
  if (value !== 0 && (Math.abs(value) >= 1e6 || Math.abs(value) < 1e-3)) {
    return value.toExponential(4);
  }
  return Number(value.toPrecision(6)).toString();
}

export function buildEngineeringReport(input: EngineeringReportInput): EngineeringReport {
  const { study, result } = input;
  const locale: ReportLocale = input.locale ?? 'en';
  const text = TEXT[locale];
  const stepLabels = STEP_LABELS[locale];
  const metricLabels = METRIC_LABELS[locale];
  const generatedAt = input.generatedAt ?? new Date();
  const fingerprint = input.fingerprint ?? engineeringFingerprint(study);
  const material = resolveMaterial(study.materials, study.materialAssignment, 0);
  const issues = validateMesh(study.mesh);
  const errors = issues.filter((issue) => issue.severity === 'error');
  const cases = ensureCase(study.cases);
  const title = `${study.name} — ${text.report_suffix}`;

  const groups = study.mesh.groups
    .slice(0, 40)
    .map((group) => `| ${group.dimension} | ${group.tag} | ${group.name} | ${group.members.length} |`)
    .join('\n');

  const materials = study.materials
    .map((item) => {
      const properties = Object.entries(item.properties)
        .map(([key, value]) => `${key}=${Array.isArray(value) ? value.join('/') : number(value)}`)
        .join(', ');
      return `| ${item.name} | ${properties || '—'} |`;
    })
    .join('\n');

  const boundary = study.boundaryConditions
    .map((condition) => {
      const components = Object.entries(condition.components)
        .map(([key, value]) => `c${key}=${number(value)}`)
        .join(', ');
      return `| ${condition.name} | ${condition.kind} | ${condition.target.dimension}:${condition.target.tag} | ${components || condition.expression || '—'} |`;
    })
    .join('\n');

  const steps = cases
    .flatMap((studyCase) => studyCase.steps)
    .map(
      (step) =>
        `| ${step.name} | ${stepLabels[step.kind] ?? step.kind} | ${step.solver.algorithm} | ${number(step.solver.tolerance)} |`,
    )
    .join('\n');

  const metrics = result
    ? Object.entries(result.metrics)
        .filter(([key]) => !['nodeCount', 'elementCount'].includes(key))
        .map(([key, value]) => `| ${metricLabels[key] ?? key} | ${number(value)} |`)
        .join('\n')
    : '';

  const lines: string[] = [
    `# ${title}`,
    '',
    `${text.generated}: ${generatedAt.toISOString()}`,
    '',
    `## ${text.model}`,
    '',
    `- ${text.source_format}: \`${study.sourceFormat}\``,
    `- ${text.mesh}: ${meshSummary(study.mesh)}`,
    `- ${text.bounds}: ${study.mesh.bounds.map(number).join(', ')}`,
    `- ${text.validation}: ${errors.length === 0 ? text.pass : text.errors!.replace('{n}', String(errors.length))}`,
    `- ${text.primary_material}: ${material?.name ?? '—'}`,
    '',
    `## ${text.materials}`,
    '',
    `| ${text.name} | ${text.properties} |`,
    '| --- | --- |',
    materials || '| — | — |',
    '',
    `## ${text.boundary}`,
    '',
    `| ${text.name} | ${text.kind} | ${text.target} | ${text.components} |`,
    '| --- | --- | --- | --- |',
    boundary || '| — | — | — | — |',
    '',
    `## ${text.steps}`,
    '',
    `| ${text.step} | ${text.kind} | ${text.algorithm} | ${text.tolerance} |`,
    '| --- | --- | --- | --- |',
    steps || '| — | — | — | — |',
    '',
    `## ${text.groups}`,
    '',
    `| ${text.dim} | ${text.tag} | ${text.name} | ${text.members} |`,
    '| --- | --- | --- | --- |',
    groups || '| — | — | — | — |',
    '',
  ];

  if (result) {
    lines.push(
      `## ${text.results}`,
      '',
      `${text.step}: **${result.stepName}** (${stepLabels[result.kind] ?? result.kind})`,
      `${text.iterations}: ${result.iterations} · ${text.residual}: ${number(result.residual)}`,
      '',
      `| ${text.metric} | ${text.value} |`,
      '| --- | --- |',
      metrics || '| — | — |',
      '',
      `${text.fields}: ${result.fields.map((field) => `${field.name} (${field.location})`).join(', ')}`,
      '',
    );
  } else {
    lines.push(`## ${text.results}`, '', text.no_solve!, '');
  }

  if (input.benchmark) {
    lines.push(
      `## ${text.benchmark}`,
      '',
      `- ${text.case}: ${input.benchmark.name}`,
      `- ${text.relative_error}: ${number(input.benchmark.relativeError)}`,
      `- ${text.observed_order}: ${input.benchmark.order === null ? '—' : number(input.benchmark.order)}`,
      '',
    );
  }

  lines.push(
    `## ${text.fingerprint}`,
    '',
    `- ${text.mesh_hash}: \`${fingerprint.meshHash}\``,
    `- ${text.case_hash}: \`${fingerprint.caseHash}\``,
    `- ${text.solver}: ${fingerprint.solver.name} ${fingerprint.solver.version} (${fingerprint.solver.algorithm}, ${text.tolerance} ${number(fingerprint.solver.tolerance)})`,
    `- ${text.materials}: ${Object.entries(fingerprint.materialHashes).map(([name, hash]) => `${name}=\`${hash}\``).join(', ') || '—'}`,
    '',
    `> ${text.footer}`,
  );

  const markdown = lines.join('\n');
  return { title, markdown, html: markdownToHtml(markdown, text.html_title!), fingerprint };
}

function markdownToHtml(markdown: string, title: string): string {
  const lines = markdown.split('\n');
  const html: string[] = [];
  let inTable = false;
  for (const line of lines) {
    if (/^\|/.test(line)) {
      if (/^\|[\s\-|]+$/.test(line)) continue;
      const cells = line.slice(1, -1).split('|').map((cell) => cell.trim());
      if (!inTable) {
        html.push('<table>');
        inTable = true;
        html.push(`<tr>${cells.map((cell) => `<th>${esc(cell)}</th>`).join('')}</tr>`);
      } else {
        html.push(`<tr>${cells.map((cell) => `<td>${esc(cell)}</td>`).join('')}</tr>`);
      }
      continue;
    }
    if (inTable) {
      html.push('</table>');
      inTable = false;
    }
    if (line.startsWith('# ')) html.push(`<h1>${esc(line.slice(2))}</h1>`);
    else if (line.startsWith('## ')) html.push(`<h2>${esc(line.slice(3))}</h2>`);
    else if (line.startsWith('> ')) html.push(`<blockquote>${esc(line.slice(2))}</blockquote>`);
    else if (line.startsWith('- ')) html.push(`<p class="report-item">${esc(line.slice(2))}</p>`);
    else if (line.trim() === '') html.push('');
    else html.push(`<p>${esc(line)}</p>`);
  }
  if (inTable) html.push('</table>');
  return `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title>
<style>
@page{size:A4;margin:18mm 16mm}
html,body{margin:0}
body{font-family:"Segoe UI","Microsoft YaHei",ui-sans-serif,system-ui,sans-serif;max-width:178mm;margin:0 auto;padding:18mm 16mm;line-height:1.65;color:#1f2933;background:#fff;-webkit-print-color-adjust:exact;print-color-adjust:exact}
h1{font-size:1.5rem;line-height:1.3;margin:0 0 .6rem;padding-bottom:.45rem;border-bottom:2px solid #1f2933}
h2{font-size:1.05rem;margin-top:1.7rem;margin-bottom:.5rem;padding-bottom:.25rem;border-bottom:1px solid #d9e2ec}
p{margin:.35rem 0}
p.report-item{margin:.2rem 0 .2rem 1rem;position:relative}
p.report-item::before{content:"•";position:absolute;left:-.9rem;color:#52606d}
table{border-collapse:collapse;width:100%;margin:.5rem 0 .9rem;font-size:.86rem}
th,td{border:1px solid #cbd2d9;padding:.32rem .5rem;text-align:left;vertical-align:top}
th{background:#eef2f6;font-weight:600}
code{background:#eef2f6;padding:.08rem .28rem;border-radius:3px;font-size:.88em}
blockquote{color:#52606d;border-left:3px solid #9fb3c8;margin:1rem 0 0;padding-left:.8rem;font-size:.88rem}
@media print{body{padding:0;max-width:none}}
</style>
</head><body>${html.join('\n')}</body></html>`;
}

/** Compact one-line status used by the right-hand panel. */
export function reportStatus(input: EngineeringReportInput): string {
  const fingerprint = engineeringFingerprint(input.study);
  return input.result
    ? `${input.result.stepName}: ${Object.keys(input.result.metrics).length} metrics`
    : `no solve; mesh ${fingerprint.meshHash}`;
}

