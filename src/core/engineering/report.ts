// Industrial analysis report (P5)
//
// Renders a self-contained Markdown / HTML report from the engineering
// study, the last solve result and the reproducibility fingerprint. Kept
// pure so the same content can be previewed, downloaded, written to the
// workspace and archived in a `.clproj` build record. `locale` defaults to
// English so existing consumers and archives stay stable.
// ==========================================================================

