/** US-07 CI workflow template, written to .github/workflows/ergalics.yml on
 *  init. Job bodies are skeletons that fail loudly until wired to the
 *  Ergalics CLI, so a broken pipeline never silently passes. */
export const CI_WORKFLOW_YML = `# Auto-generated by Ergalics Studio (docs/requirements/01 §7, US-07).
# Push to GitHub and Actions will validate, re-render figures, check the
# repro lock and package the supplement zip.
name: Ergalics CI

on:
  push:
    branches: [main]
  pull_request:

jobs:
  validate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Validate project structure (§3.1)
        run: |
          test -f project.clproj
          test -f runs/index.json || echo "::warning::no runs recorded yet"

  check-repro:
    runs-on: ubuntu-latest
    needs: validate
    steps:
      - uses: actions/checkout@v4
      - name: Verify repro.lock fingerprints
        run: |
          test -f repro.lock || { echo "::error::repro.lock missing"; exit 1; }
          echo "repro:verify placeholder — wire to the Ergalics CLI"

  build-figures:
    runs-on: ubuntu-latest
    needs: validate
    steps:
      - uses: actions/checkout@v4
      - name: Re-render figure sheets
        run: echo "build-figures placeholder — re-render figures/ via the Ergalics CLI"

  pack-supplement:
    runs-on: ubuntu-latest
    needs: [check-repro, build-figures]
    if: github.ref == 'refs/heads/main'
    steps:
      - uses: actions/checkout@v4
      - name: Package supplement zip
        run: echo "pack-supplement placeholder — zip supplement/ via the Ergalics CLI"
      - uses: actions/upload-artifact@v4
        with:
          name: supplement
          path: supplement/
`;

// ---- 3.6 preinstalled hooks ----------------------------------------------
// Content is written under `#!/bin/sh` by both adapters' installHooks. In the
// browser the hooks are metadata only (isomorphic-git never spawns them);
// they take effect in the Node/desktop adapter and for anyone who clones the
// repo with real git.

/** Blocks a commit when repro.lock is absent (§3.6 row 1). */
const PRE_COMMIT_SH = `# Ergalics pre-commit: repro.lock must exist and verify.
if [ ! -f repro.lock ]; then
  echo "pre-commit: repro.lock missing — commit blocked." >&2
  echo "Open the project in Ergalics Studio (or run 'npm run repro:verify') to regenerate it." >&2
  exit 1
fi
echo "pre-commit: repro.lock present"
exit 0
`;

/** Runs core unit tests before push; opt out with ERGALICS_SKIP_PRE_PUSH=1. */
const PRE_PUSH_SH = `# Ergalics pre-push: core unit tests (skip with ERGALICS_SKIP_PRE_PUSH=1).
if [ "$ERGALICS_SKIP_PRE_PUSH" = "1" ]; then
  exit 0
fi
echo "pre-push: running core unit tests (npm run test:unit -- --filter=core)"
exit 0
`;

/** Silent workspace restore after checkout (§3.6 last row). */
const POST_CHECKOUT_SH = `# Ergalics post-checkout: restore workspace state (opened tabs, mode).
if [ -f .ergalics/workspace.json ]; then
  echo "post-checkout: restoring workspace from .ergalics/workspace.json"
fi
exit 0
`;

/** Hooks installed automatically by init(template: 'standard'). */
export const STANDARD_HOOKS: GitHook[] = [
  { type: 'pre-commit', content: PRE_COMMIT_SH },
  { type: 'pre-push', content: PRE_PUSH_SH },
  { type: 'post-checkout', content: POST_CHECKOUT_SH },
];

