// ==========================================================================
// CI web-build placeholder for the WASM core (scripts/make-wasm-stub.mjs)
//
// `vite build` chunks the dynamic import in src/core/wasm.ts into
// dist/assets/ergalics_core-*.js, which requires the source module to exist.
// In CI (no Rust toolchain) we cannot run `build:wasm`, so when the real
// build artifact is absent we emit a functional stub: it satisfies the build,
// and at runtime the app degrades to CPU/extension-based detection exactly
// as it does when WASM is unavailable.
//
// Idempotent: if a real module is already present (local `npm run build`,
// the deploy workflow), this script does nothing.
// ==========================================================================

import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const nativeDir = fileURLToPath(new URL('../src/native/', import.meta.url));
const target = new URL('../src/native/ergalics_core.js', import.meta.url);

if (existsSync(target)) {
  console.log('[make-wasm-stub] real wasm module present — skipping stub');
  process.exit(0);
}

const stub = `// Generated by scripts/make-wasm-stub.mjs (CI web build; no Rust toolchain).
// Placeholder for the Rust→WASM core. At runtime the app treats a missing
// WASM module as "unavailable" and falls back to CPU / extension detection.

export default async function init() {}

export function core_version() {
  return 'wasm-stub';
}

export function detect_file_kind() {
  return undefined; // fall back to extension-based detection
}

export function log() {}
`;

mkdirSync(nativeDir, { recursive: true });
writeFileSync(target, stub, 'utf8');
console.log('[make-wasm-stub] wrote src/native/ergalics_core.js placeholder');
