// ==========================================================================
// CI / fresh-checkout placeholder for the WASM core (scripts/make-wasm-stub.mjs)
//
// `src/core/wasm.ts` dynamically imports `../native/ergalics_core.js`. A pure
// source checkout does not contain that generated module (nor does it ship a
// Rust toolchain), so both `vite dev` and `vite build` need a placeholder:
// without one the browser reports a failed import before the app can degrade
// gracefully to CPU / extension-based detection.
//
// Idempotent: if a real module is already present (local `npm run build:wasm`,
// the deploy workflow), this function does nothing. Exported so Vite can call
// it on dev-server start and at build time, not only from the CLI.
// ==========================================================================

import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const target = fileURLToPath(new URL('../apps/studio/src/native/ergalics_core.js', import.meta.url));

const stub = `// Generated by scripts/make-wasm-stub.mjs (no Rust toolchain).
// Placeholder for the Rust→WASM core. At runtime the app treats a missing
// WASM module as "unavailable" and falls back to CPU / extension detection.

export default async function init() {}

export function core_version() {
  return 'wasm-stub';
}

export function detect_file_kind() {
  return undefined; // fall back to extension-based detection
}

export function log() {}
`;

/** Ensure the import target exists. Returns true when a stub was written. */
export function ensureWasmStub() {
  if (existsSync(target)) return false;
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, stub, 'utf8');
  console.log('[make-wasm-stub] wrote apps/studio/src/native/ergalics_core.js placeholder');
  return true;
}

// Run only as a CLI command (`npm run build:web`), not when imported by Vite.
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (!existsSync(target)) ensureWasmStub();
  else console.log('[make-wasm-stub] real wasm module present — skipping stub');
}
