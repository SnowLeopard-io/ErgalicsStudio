// ==========================================================================
// Standalone reproduction script generator (FR-5)
//
// Emits a pure-standard-library Python script. Metrics with a recorded
// formula are recomputed and compared; metrics without one are printed as
// explicitly unverifiable with the alternative verification step, so nothing
// is silently dropped.
// ==========================================================================

import { canonicalJSON } from './canonical';
import type { ResultRecord } from './types';

function pythonLiteral(value: unknown): string {
  return JSON.stringify(value ?? null);
}

export function buildReproductionScript(record: ResultRecord): string {
  const lines: string[] = [];
  lines.push('#!/usr/bin/env python3');
  lines.push('# Standalone reproduction script generated by Ergalics Studio');
  lines.push(`# resultId: ${record.resultId}`);
  lines.push(`# dataHash: ${record.input.dataHash || '(no input file recorded)'}`);
  lines.push(`# plugin: ${record.pluginId} v${record.pluginVersion}`);
  lines.push(`# createdAt: ${record.createdAt}`);
  lines.push('');
  lines.push('import json');
  lines.push('import math');
  lines.push('');
  lines.push(`PARAMS = ${pythonLiteral(record.params)}`);
  lines.push(`RECORDED = ${pythonLiteral(
    Object.fromEntries(record.metrics.map((m) => [m.key, m.value])),
  )}`);
  lines.push('p = PARAMS');
  lines.push('m = RECORDED');
  lines.push('');
  lines.push('def check(label, value, expected, tolerance=1e-9):');
  lines.push('    try:');
  lines.push('        actual = float(value)');
  lines.push('        target = float(expected)');
  lines.push('        ok = math.isclose(actual, target, rel_tol=tolerance, abs_tol=tolerance)');
  lines.push('    except (TypeError, ValueError):');
  lines.push('        actual, target, ok = value, expected, str(value) == str(expected)');
  lines.push(
    '    print(f"{label}: computed={actual!r} recorded={target!r} " ' +
      '+ f"{\'MATCH\' if ok else \'MISMATCH\'}")',
  );
  lines.push('');
  lines.push('# --- recomputable metrics -------------------------------------------');

  let recomputable = 0;
  for (const m of record.metrics) {
    if (m.formula) {
      // JSON-escaped expression is a valid Python string literal. Only the
      // narrow expression grammar accepted by evaluateFormula reaches here.
      lines.push(`check(${pythonLiteral(m.key)}, (${m.formula}), RECORDED[${pythonLiteral(m.key)}])`);
      recomputable += 1;
    } else {
      lines.push(
        `# UNVERIFIABLE: ${m.key} has no machine-checkable formula. ` +
          `Re-run ${record.pluginId} in the app and compare its ${m.label} value.`,
      );
      lines.push(
        `print("UNVERIFIABLE: ${m.key} — re-run the plugin; ` +
          `no standalone formula was published")`,
      );
    }
  }
  if (recomputable === 0) {
    lines.push('# No standalone formula is available for any metric in this result.');
    lines.push('# Alternative: download the recorded inputs and re-run the same plugin');
    lines.push('# with the parameter snapshot below, then compare the metric strip.');
  }
  lines.push('');
  lines.push('print("Parameters:", json.dumps(PARAMS, sort_keys=True, ensure_ascii=False))');
  lines.push(
    `print("Provenance:", ${pythonLiteral(
      canonicalJSON({ resultId: record.resultId, dataHash: record.input.dataHash }),
    )})`,
  );
  return `${lines.join('\n')}\n`;
}
